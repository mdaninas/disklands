const sorted = english.sort((a, b) => b[0].length - a[0].length);
const replacements = new Map(sorted);
const pattern = new RegExp(sorted.map(([source]) => source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

export function toEnglish(value) {
  return String(value).replace(pattern, source => replacements.get(source));
}

export function localize(root, language) {
  if (language !== 'en' || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest('.tile-label, .directory-path-label, .map-crumbs button, .file-name b, .history-path span, .detail-path, .details-drawer h2, .scan-progress small, .compact-folder-list button > span:nth-of-type(2)')) continue;
    if (node.parentElement?.matches('.file-name small') && /[\\/]/.test(node.textContent)) continue;
    node.textContent = toEnglish(node.textContent);
  }
  for (const element of [root, ...root.querySelectorAll('[title], [aria-label], [placeholder]')]) {
    if (element.matches('.file-name b, .file-name small, .directory-path, .map-crumbs button, .history-path span, .map-tile, .scan-progress small, .row-more')) continue;
    for (const name of ['title', 'aria-label', 'placeholder']) {
      const value = element.getAttribute(name);
      if (value) element.setAttribute(name, toEnglish(value));
    }
  }
}
